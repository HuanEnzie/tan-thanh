import json, os
H = os.path.dirname(os.path.abspath(__file__)); D = os.path.join(H, 'content15')
def L(n): return json.load(open(os.path.join(D, n + '.json'), encoding='utf-8'))
C = {'talents': {}, 'backstory': {}, 'relations': {}}
for r in ('md', 'tt', 'sl'):
    for k in ('talents', 'backstory', 'relations'):
        p = os.path.join(D, f'{k}_{r}.json')
        if os.path.exists(p): C[k][r] = L(f'{k}_{r}')
if os.path.exists(os.path.join(D, 'traits.json')): C['traits'] = L('traits')['traits']
open(os.path.join(H, '..', 'js', 'content15.js'), 'w', encoding='utf-8').write('// generated by tools/build_content15.py from tools/content15/*.json (text written with GPT)\nconst CONTENT15 = ' + json.dumps(C, ensure_ascii=False, separators=(',', ':')) + ';\n')
print({k: list(v) if isinstance(v, dict) else len(v) for k, v in C.items()})
