"""Battle cries for every ultimate / mana skill, male + female, packed into ONE file: assets/audio/voice17.mp3 + js/voice17.js (offsets).
The Gemini key comes only from the GEMINI_API_KEY environment variable (never printed)."""
import os, sys, json, pathlib, subprocess, concurrent.futures as cf
SK = pathlib.Path.home() / ".claude/skills/video-quang-cao-app-saas/scripts"
sys.path.insert(0, str(SK))
import gemini_tts as g
H = pathlib.Path(__file__).parent; OUT = H / 'logs' / 'voice17'; OUT.mkdir(parents=True, exist_ok=True)
KEY = os.environ['GEMINI_API_KEY']
MODEL = 'gemini-3.8-flash-tts'
VOICES = {'m': 'Algenib', 'f': 'Kore'}
LINES = {
 'u_md': 'Không kích! Khai hỏa!', 'u_tt': 'Vạn kiếm quy tông!', 'u_sl': 'Arise!',
 'meteor_md': 'Mưa tên lửa!', 'meteor_tt': 'Thiên hỏa lưu tinh!', 'meteor_sl': 'Mưa thiên thạch!',
 'frost_md': 'Bom băng!', 'frost_tt': 'Huyền băng trận!', 'frost_sl': 'Đóng băng tuyệt đối!',
 'chain_md': 'Súng điện chuỗi!', 'chain_tt': 'Cửu thiên lôi kiếp!', 'chain_sl': 'Lôi ấn!',
 'hole_md': 'Lựu đạn trọng lực!', 'hole_tt': 'Hắc động thôn thiên!', 'hole_sl': 'Kiếp hư không!',
 'heal_md': 'Hồi phục!', 'heal_tt': 'Hồi xuân thuật!', 'heal_sl': 'Ban phước!',
 'blades_md': 'Lưỡi cưa xoay!', 'blades_tt': 'Luân hồi kiếm trận!', 'blades_sl': 'Vũ điệu song kiếm!',
 'dash_md': 'Lướt sát thủ!', 'dash_tt': 'Thuấn ảnh sát!', 'dash_sl': 'Bộ pháp bóng ma!',
 'inferno_md': 'Bom xăng hủy diệt!', 'inferno_tt': 'Tam muội chân hỏa!', 'inferno_sl': 'Hỏa ngục!',
}
STYLE = {'u_sl': '[a deep, low, menacing voice that whispers then commands with a dark echo, English]'}
DEF = '[shouting a fierce, powerful battle cry in Vietnamese, short and dramatic, strong echo]'

def one(k, gdr):
    out = OUT / f'{k}_{gdr}.wav'
    if out.exists() and out.stat().st_size > 2000: return k, gdr, out
    g.tts(LINES[k], VOICES[gdr], out, KEY, MODEL, STYLE.get(k, DEF))
    return k, gdr, out
jobs = [(k, d) for k in LINES for d in 'mf']
done = {}
with cf.ThreadPoolExecutor(3) as ex:
    for k, d, p in ex.map(lambda a: one(*a), jobs): done[(k, d)] = p
# trim silence, normalise, concat with 0.12 s gaps
off, t, names, parts = {}, 0.0, [], []
for (k, d), p in done.items():
    tr = OUT / f'{k}_{d}_t.wav'
    subprocess.run(['ffmpeg', '-y', '-v', 'error', '-i', str(p), '-af', 'silenceremove=start_periods=1:start_threshold=-45dB:stop_periods=1:stop_threshold=-45dB:stop_duration=0.15,loudnorm=I=-14:TP=-1.5', '-ar', '44100', '-ac', '1', str(tr)], check=True)
    dur = float(subprocess.check_output(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', str(tr)]).decode().strip())
    off[f'{k}_{d}'] = [round(t, 3), round(dur, 3)]; t += dur + 0.12; parts.append(tr)
lst = OUT / 'list.txt'; sil = OUT / 'sil.wav'
subprocess.run(['ffmpeg', '-y', '-v', 'error', '-f', 'lavfi', '-i', 'anullsrc=r=44100:cl=mono', '-t', '0.12', str(sil)], check=True)
lst.write_text(''.join(f"file '{p.as_posix()}'\nfile '{sil.as_posix()}'\n" for p in parts), encoding='utf-8')
mp3 = H.parent / 'assets' / 'audio' / 'voice17.mp3'
subprocess.run(['ffmpeg', '-y', '-v', 'error', '-f', 'concat', '-safe', '0', '-i', str(lst), '-b:a', '64k', str(mp3)], check=True)
(H.parent / 'js' / 'voice17.js').write_text('// generated by tools/gen_voice17.py\nconst VOICE17 = ' + json.dumps(off, separators=(',', ':')) + ';\n', encoding='utf-8')
print(len(off), 'clips', round(t, 1), 's', mp3.stat().st_size // 1024, 'KB')
