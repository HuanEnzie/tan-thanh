"""Pack round-7 sprites into a few atlases (the artifact host caps the number of files)."""
import os, json
from PIL import Image
H = os.path.dirname(os.path.abspath(__file__)); IMG = os.path.join(H, '..', 'assets', 'img')
groups = {'atlas8_fx': [f'fx_{a}_{i}' for a in ['exp','slash','hit','frost','bolt','meteor','vortex','heal','portal','lvl','fire','poison'] for i in range(6)],
          'atlas8_common': [f'pj_{i}' for i in range(12)] + [f'ic_{i}' for i in range(16)]}
for r in ['md', 'tt', 'sl']:
    groups['atlas8_' + r] = [f'{r}_bm_{i}' for i in range(6)]
out = {}
for g, names in groups.items():
    ims = [(n, Image.open(os.path.join(IMG, n + '.png')).convert('RGBA')) for n in names]
    W = 1024; x = y = rowh = 0; pos = {}
    for n, im in sorted(ims, key=lambda t: -t[1].height):
        if x + im.width > W: x = 0; y += rowh + 2; rowh = 0
        pos[n] = (x, y, im.width, im.height); x += im.width + 2; rowh = max(rowh, im.height)
    sheet = Image.new('RGBA', (W, y + rowh))
    for n, im in ims: sheet.paste(im, pos[n][:2])
    sheet.save(os.path.join(IMG, g + '.png'), optimize=True)
    out[g] = pos
    print(g, sheet.size, os.path.getsize(os.path.join(IMG, g + '.png')) // 1024, 'KB')
open(os.path.join(H, '..', 'js', 'atlas8.js'), 'w', encoding='utf-8').write("// generated by tools/atlas8.py\nObject.assign(ATLAS6, " + json.dumps(out, separators=(',', ':')) + ");\n")
