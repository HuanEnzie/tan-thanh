"""Round 17: slice sea creature + boat sheets into {r}_sea_{0-5} and {r}_boat, then pack atlas17_{r}.png + js/atlas17.js."""
import os, sys, json
import numpy as np
from PIL import Image
from scipy import ndimage
sys.path.insert(0, os.path.dirname(__file__))
from process import key_magenta, RAW, OUT
W = [200, 140, 160, 230, 440, 150, 250]   # target file width of each sprite (the game draws sprites at half size)


def parts(sheet, want, dilate=14):
    a = np.asarray(key_magenta(Image.open(os.path.join(RAW, sheet + '.png')))).copy()
    a[..., 3] = np.where(a[..., 3] >= 128, 255, 0)
    m = a[..., 3] > 0
    lab, _ = ndimage.label(ndimage.binary_dilation(m, iterations=dilate))
    objs = []
    for i, sl in enumerate(ndimage.find_objects(lab)):
        keep = (lab[sl] == i + 1) & m[sl]
        if keep.sum() < 2500: continue
        ys, xs = np.nonzero(keep)
        y0, y1, x0, x1 = ys.min() + sl[0].start, ys.max() + sl[0].start + 1, xs.min() + sl[1].start, xs.max() + sl[1].start + 1
        crop = a[y0:y1, x0:x1].copy(); crop[..., 3] = np.where((lab[y0:y1, x0:x1] == i + 1) & (crop[..., 3] > 0), 255, 0)
        objs.append(((y0 + y1) / 2, (x0 + x1) / 2, y1 - y0, Image.fromarray(crop, 'RGBA')))
    objs.sort(key=lambda o: o[0])
    rows, cur = [], []
    for o in objs:
        if cur and abs(o[0] - np.mean([c[0] for c in cur])) > 0.45 * max(c[2] for c in cur): rows.append(cur); cur = []
        cur.append(o)
    if cur: rows.append(cur)
    out = [o[3] for r in rows for o in sorted(r, key=lambda o: o[1])]
    if len(out) != want: print('!!', sheet, 'found', len(out), 'expected', want)
    return out


groups = {}
for r in ('md', 'tt', 'sl'):
    p = os.path.join(RAW, f'sea17_{r}.png')
    if not os.path.exists(p): continue
    ps = []
    for d in (14, 10, 8, 6, 5, 4):
        ps = parts(f'sea17_{r}', 7, d)
        if len(ps) == 7: break
    if len(ps) != 7: continue
    names = [f'{r}_sea_{i}' for i in range(6)] + [f'{r}_boat']
    for n, im, w in zip(names, ps, W):
        im = im.resize((w, max(1, round(im.height * w / im.width))), Image.LANCZOS); im.save(os.path.join(OUT, n + '.png'))
    groups['atlas17_' + r] = names
out = {}
for g, names in groups.items():
    ims = [(n, Image.open(os.path.join(OUT, n + '.png')).convert('RGBA')) for n in names]
    Wd = 1024; x = y = rowh = 0; pos = {}
    for n, im in sorted(ims, key=lambda t: -t[1].height):
        if x + im.width > Wd: x = 0; y += rowh + 2; rowh = 0
        pos[n] = (x, y, im.width, im.height); x += im.width + 2; rowh = max(rowh, im.height)
    sheet = Image.new('RGBA', (Wd, y + rowh))
    for n, im in ims: sheet.paste(im, pos[n][:2])
    sheet.save(os.path.join(OUT, g + '.png'), optimize=True); out[g] = pos
    print(g, sheet.size, os.path.getsize(os.path.join(OUT, g + '.png')) // 1024, 'KB')
open(os.path.join(H := os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'), 'js', 'atlas17.js'), 'w', encoding='utf-8').write("// generated by tools/build17.py\nObject.assign(ATLAS6, " + json.dumps(out, separators=(',', ':')) + ");\n")
